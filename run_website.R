## Builds the site: writes _quarto.yml from the template below (with the
## Projects menu generated from the CV spreadsheet), then renders everything
## into docs/. This file is the source of truth for _quarto.yml, so make
## config changes here; hand edits to _quarto.yml are overwritten.
## Run from the repo root: Rscript run_website.R
##
## Look and feel: the "Night and Day" theme in styles/*.scss (listed under
## format.html.theme below; see the class list at the top of styles/bml.scss).
## The navbar, footer and title banners are configured here; pages carry no
## CSS of their own.

## load packages and setup
source("package_setup.R", echo = FALSE)


projects <- read_excel(cvpath,
                       sheet = "Projects")
projects <- as.data.table(projects)[nzchar(Summary) & !is.na(Summary)]
projects <- projects[order(-Status, -Started)]

navItems <- function(type) {
  paste(projects[Primary == 1 & Type == type, sprintf(
'          - text: "%s"
            href: projects.qmd#%s',
Name, projectAnchor(Name))], collapse = "\n")
}

## Navbar: logo mark + lab name, then Research, Projects (menu from the
## Projects sheet), Team, Values and a "Get involved" pill (.bml-nav-cta) to
## join.qmd. The CV is linked from the footer.
## Footer: Acknowledgement of Country (Monash University's wording), three link
## columns (the Get involved column links each section of join.qmd) and the
## copyright line, laid out by the footer rules in styles/bml.scss. Its
## markdown is Pandoc's, so fenced divs and spans work. The email link comes
## from labEmail (package_setup.R); its text has a <wbr> after the "@" (raw
## HTML: markdown can't mark a line-break opportunity), so the narrow column
## breaks it there rather than mid-word.
## open-graph (with site-url) gives every page title and description tags, so
## shared links preview well (each page sets description-meta and
## open-graph: description in its front matter). back-to-top-navigation adds a
## "Back to top" pill (styled in styles/bml.scss) when a long page is scrolled
## back up.
