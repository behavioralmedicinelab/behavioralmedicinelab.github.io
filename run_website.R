## Builds the site: writes _quarto.yml from the template below (with the
## Projects menu generated from the CV spreadsheet), then renders everything
## into docs/. This file is the source of truth for _quarto.yml, so make
## config changes here; hand edits to _quarto.yml are overwritten.
## Run from the repo root: Rscript run_website.R
##
## Look and feel: the "Night and Day" theme in styles/*.scss (listed under
## format.html.theme below; see the class list at the top of styles/bml.scss).
## The navbar, footer and title banners are configured here; pages carry no
## CSS of their own.

## load packages and setup
source("package_setup.R", echo = FALSE)


projects <- read_excel(cvpath,
                       sheet = "Projects")
projects <- as.data.table(projects)[nzchar(Summary) & !is.na(Summary)]
projects <- projects[order(-Status, -Started)]

navItems <- function(type) {
  paste(projects[Primary == 1 & Type == type, sprintf(
'          - text: "%s"
            href: projects.qmd#%s',
Name, projectAnchor(Name))], collapse = "\n")
}

